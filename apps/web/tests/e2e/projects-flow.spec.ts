import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { randomUUID } from "node:crypto";

test("Projects persist GitHub links, show readable dates and retain saved text across editing", async ({ page, request }, info) => {
  await request.post("http://127.0.0.1:8300/__test", { data: { confirmEmail: true } });
  await page.goto("/sign-up");
  await page.getByLabel("Email", { exact: true }).fill(`projects-${randomUUID()}@example.invalid`);
  await page.getByLabel("Password", { exact: true }).fill("Local-E2E-Fixture-Only-2026");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByText(/Check your email to confirm/)).toBeVisible();
  const control = await (await request.get("http://127.0.0.1:8300/__test")).json();
  await page.goto(`/auth/callback?code=${encodeURIComponent(control.confirmationCode)}`);
  await page.getByLabel("Bachelor's", { exact: true }).check();
  for (const [label, value] of [["University", "Fixture University"], ["Field of study", "Computer Science"], ["Graduation year", "2027"], ["City", "Berlin, Germany"]]) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole("button", { name: "Show my internships", exact: true }).click();
  await expect(page).toHaveURL(/\/jobs/);
  await page.goto("/profile");
  await page.getByRole("button", { name: "Add project", exact: true }).click();
  const title = "Student Opportunity Dashboard";
  const url = "https://github.com/example-student/opportunity-dashboard";
  const description = "Build accessible discovery tools for students.\n\n• Support reliable data validation.\n• Review interface changes with a small team.\n".repeat(4) + "This is the final synthetic project sentence.";
  await page.getByLabel("Project name (required)", { exact: true }).fill(title);
  await page.getByLabel("Start date (optional)", { exact: true }).fill("2026-10");
  await page.getByLabel("Ongoing", { exact: true }).check();
  await page.getByLabel("Description (optional)", { exact: true }).fill(description);
  await page.getByLabel("GitHub / repository URL (optional)", { exact: true }).fill(url);
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText("Project saved.", { exact: true })).toBeVisible();
  await page.reload();
  const card = page.getByRole("article").filter({ has: page.getByRole("heading", { name: title, exact: true }) });
  await expect(card.getByText("Oct 2026 – Present", { exact: true })).toBeVisible();
  await expect(card.getByRole("link", { name: /github.com\/example-student/ })).toHaveAttribute("href", url);
  await expect(card.getByText(/This is the final synthetic project sentence/)).toHaveCount(0);
  const more = card.getByRole("button", { name: `Show more about ${title}`, exact: true });
  await more.click();
  await expect(card.getByText(/This is the final synthetic project sentence/)).toBeVisible();
  await card.getByRole("button", { name: `Show less about ${title}`, exact: true }).click();
  await card.getByRole("button", { name: `Edit ${title}`, exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByLabel("GitHub / repository URL (optional)", { exact: true })).toHaveValue(url);
  await page.getByLabel("GitHub / repository URL (optional)", { exact: true }).fill("javascript:alert(1)");
  await page.getByRole("button", { name: "Save", exact: true }).click();
  await expect(page.getByText(/Enter an absolute HTTP\/HTTPS URL/)).toBeVisible();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(card.getByRole("link", { name: /github.com\/example-student/ })).toHaveAttribute("href", url);
  await card.scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("projects.png"), scale: "css", style: "nextjs-portal { visibility: hidden }" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze();
  expect(axe.violations).toEqual([]);
});
